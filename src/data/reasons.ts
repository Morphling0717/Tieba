export const REASON_RULES: ReasonRule[] = REASON_CATEGORIES.flatMap(
  ({ id: categoryId, title: categoryTitle }) =>
    REASON_TEXTS[categoryId].map((text, index) => ({
      id: `${categoryId}.${String(index + 1).padStart(2, "0")}`,
      categoryId,
      categoryTitle,
      item: index + 1,
      text,
      version: REASON_VERSION,
    })),
);

const REASON_BY_ID = new Map(REASON_RULES.map((reason) => [reason.id, reason]));

export function getReasonById(id: string): ReasonRule | undefined {
  return REASON_BY_ID.get(id);
}
